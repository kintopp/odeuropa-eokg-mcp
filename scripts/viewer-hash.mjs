// sha256 over the viewer sources and the installed ext-apps version; stamped into the built page and checked by test/viewer_build.test.js.

import { createHash } from 'node:crypto';
import { readFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const VIEWER_SRC_DIR = join(ROOT, 'apps', 'image-viewer');
export const VIEWER_HTML = join(ROOT, 'src', 'apps', 'image-viewer.html');
export const STAMP_RE = /^<!-- generated by npm run build:viewer; source sha256:([0-9a-f]{64}) -->/;

export function viewerSourceHash() {
  const h = createHash('sha256');
  for (const name of readdirSync(VIEWER_SRC_DIR).sort()) {
    h.update(`${name}\0`);
    h.update(readFileSync(join(VIEWER_SRC_DIR, name)));
    h.update('\0');
  }
  const pkg = JSON.parse(readFileSync(join(ROOT, 'node_modules', '@modelcontextprotocol', 'ext-apps', 'package.json'), 'utf8'));
  h.update(`ext-apps@${pkg.version}`);
  return h.digest('hex');
}
