// Builds apps/image-viewer/ into the committed, stamped src/apps/image-viewer.html.

import { readFileSync, writeFileSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';
import { viewerSourceHash, VIEWER_SRC_DIR, VIEWER_HTML } from './viewer-hash.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
await build({ configFile: join(VIEWER_SRC_DIR, 'vite.config.mjs'), logLevel: 'warn' });

const built = join(root, 'src', 'apps', 'index.html');
const html = readFileSync(built, 'utf8');
rmSync(built);
writeFileSync(VIEWER_HTML, `<!-- generated by npm run build:viewer; source sha256:${viewerSourceHash()} -->\n${html}`);
console.error(`wrote ${VIEWER_HTML} (${Math.round((html.length / 1024))} KB)`);
